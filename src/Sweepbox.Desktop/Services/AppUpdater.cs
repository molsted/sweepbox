using System.Reflection;
using System.Runtime.InteropServices;
using Avalonia;
using Avalonia.Controls;
using Avalonia.Platform;
using NetSparkleUpdater;
using NetSparkleUpdater.Enums;
using NetSparkleUpdater.SignatureVerifiers;
using Sweepbox.Core.Settings;

namespace Sweepbox.Desktop.Services;

/// <summary>Self-updating via NetSparkle: checks a signed appcast published with each release.</summary>
public sealed class AppUpdater
{
    private const string Repo = "molsted/sweepbox";

    private readonly SettingsStore _settings;
    private readonly WindowIcon _icon;
    private readonly Action _quit;
    private SparkleUpdater? _sparkle;
    private bool _loopRunning;

    public AppUpdater(SettingsStore settings, WindowIcon icon, Action quit)
    {
        _settings = settings;
        _icon = icon;
        _quit = quit;
    }

    /// <summary>One signed appcast per OS and architecture, generated by the release workflow.</summary>
    public static string AppCastUrl
    {
        get
        {
            var os = OperatingSystem.IsMacOS() ? "macos" : "windows";
            var arch = RuntimeInformation.ProcessArchitecture.ToString().ToLowerInvariant();
            return $"https://github.com/{Repo}/releases/latest/download/appcast-{os}-{arch}.xml";
        }
    }

    /// <summary>Starts or stops the automatic check loop to match the SelfUpdate setting.</summary>
    public void UpdateAutomatic()
    {
        if (_settings.Current.SelfUpdate)
        {
            if (_sparkle is null)
                _sparkle = CreateSparkle();
            if (!_loopRunning)
            {
                _ = _sparkle.StartLoop(true, true);
                _loopRunning = true;
            }
        }
        else if (_loopRunning)
        {
            _sparkle?.StopLoop();
            _sparkle = null; // a stopped loop must not be restarted on the same instance
            _loopRunning = false;
        }
    }

    /// <summary>The "Check for Updates…" menu item: shows NetSparkle's UI and reports the outcome.</summary>
    public void CheckAtUserRequest()
    {
        if (PublicKey is null)
        {
            Notifier.Show("Updates are not configured", "This build cannot verify signed updates. Reinstall from the website.");
            return;
        }
        _sparkle ??= CreateSparkle();
        _ = _sparkle.CheckForUpdatesAtUserRequest(true); // a manual check ignores the skipped-version list
    }

    private SparkleUpdater CreateSparkle()
    {
        var sparkle = new SweepboxSparkleUpdater(AppCastUrl, new Ed25519Checker(SecurityMode.Strict, PublicKey), _quit)
        {
            UIFactory = new SweepboxUIFactory(_icon),
            // The installers start the new version themselves; on macOS the DMG is opened for a drag-install.
            RelaunchAfterUpdate = false,
        };
        sparkle.CloseApplication += () => _quit(); // NetSparkle launches the installer only after we exit
        return sparkle;
    }

    /// <summary>The Ed25519 public key committed by the "Sparkle update keys" workflow; null while it is still a placeholder.</summary>
    private static string? PublicKey
    {
        get
        {
            var assembly = typeof(AppUpdater).Assembly;
            var name = assembly.GetManifestResourceNames().FirstOrDefault(n => n.EndsWith("sparkle-public-key.txt", StringComparison.Ordinal));
            if (name is null)
                return null;
            using var stream = assembly.GetManifestResourceStream(name)!;
            using var reader = new StreamReader(stream);
            var key = reader.ReadToEnd().Split('\n').Select(l => l.Trim())
                .FirstOrDefault(l => l.Length > 0 && !l.StartsWith('#'));
            if (key is null)
                return null;
            try
            {
                return Convert.FromBase64String(key).Length == 32 ? key : null;
            }
            catch (FormatException)
            {
                return null;
            }
        }
    }
}
